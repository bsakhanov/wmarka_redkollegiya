/**
 * Правила редакции новостного сайта — то, что не норма языка, а почерк издания: никаких «сегодня» и «вчера», «в ходе» не
 * употребляем, «млн» и «км» в тексте полностью, соцсети латиницей, «Интернет» с прописной, должности и акиматы со строчной,
 * города без слова «город», адресные слова полностью. Формат правил — как в Rules: [код, выражение, правка, слой, вес, флаги].
 *
 * Группы включаются по отдельности: time, style, names, units. Внутри цитат правила работают, если у правила есть флаг quotes:
