    private const NUM = '(\d{1,3}(?:[\x{20}\x{A0}]\d{3})+|\d+)((?:[.,]\d+)?)';

    /** @return array<int, array> */
    public static function rules(array $groups): array
    {
        $out = [];

        if (\in_array('time', $groups, true)) {
            $out[] = ['R-TIME-REL', '/\b(?:[Сс]егодня(?:шн\w+)?|[Вв]чера(?:шн\w+)?|[Зз]автра(?:шн\w+)?|[Пп]ослезавтра|[Пп]озавчера|[Нн]а днях|[Нн]а (?:этой|прошлой|следующей) неделе|[Вв] (?:эти|прошлые|минувшие|ближайшие) выходные)\b/u', null, 'house', 'warn', ['quotes']];
        }

        if (\in_array('style', $groups, true)) {
            $out[] = ['R-VHODE', '/\b([Вв]) ходе\b/u', static fn (array $m): string => ($m[1] === 'В' ? 'Во' : 'во') . ' время', 'house', 'fix', ['quotes']];
            $out[] = ['R-OZVUCH', '/\bозвуч(?:ил|ила|или|ило|ено|ена|ены|ен|ивать|ивает|ивают|ить|енный|енная|енные|енных)\b/iu', null, 'house', 'info', ['quotes']];
            // «на площадке СЦК» — да; «на площадке KASE» — торговая площадка биржи, это термин
            $out[] = ['R-PLOSCH', '/\bна площадке(?=[\x{20}\x{A0}]+(?:\p{Lu}|«))(?![^.!?\n]{0,60}(?:бирж|Exchange|KASE|AIX|LSE|NYSE|Nasdaq|MOEX))/u', null, 'house', 'info', ['quotes']];
            $out[] = ['R-PASSIVE', '/\b(?:[Бб]ыл[аио]?|[Нн]ами)[\x{20}\x{A0}]+(\p{Ll}{3,}(?:ан|ян|ен|ён|т)[аоы]?)\b/u', static fn (array $m) => null, 'house', 'info', ['quotes', 'passive']];
            $out[] = ['R-DR', '/\bи[\x{20}\x{A0}]+др\./u', null, 'house', 'info', ['quotes']];
            $out[] = ['R-NAPOMNIM', '/\b[Нн]апомним\b/u', null, 'house', 'info', []];
        }

        if (\in_array('names', $groups, true)) {
            foreach ([
                ['/\b[Фф]ейсбук\w*/u', 'Facebook'],
                ['/\b[Ии]нстаграм\w*/u', 'Instagram'],
                ['/\b(?:[Вв]атсапп?|[Вв]отсап|[Уу]отсап|[Вв]ацап)\w*/u', 'WhatsApp'],
                ['/\b[Тт]елеграм(?:а|е|у|ом)?(?![\p{L}])|\b[Тт]елеграмм(?=-)/u', 'Telegram'],
                ['/\b[Тт]в[иі]ттер\w*/u', 'X'],
                ['/\b(?:[Юю]туб|[Юю]тьюб)\w*/u', 'YouTube'],
                ['/\b[Тт]ик[Тт]ок\w*/u', 'TikTok'],
            ] as [$re, $to]) {
                $out[] = ['R-SOC', $re, $to, 'house', 'fix', ['quotes', 'auto']];
            }

            $out[] = ['R-INET', '/\bинтернет(?:а|у|ом|е)?(?![\p{L}-])/u', static fn (array $m): string => 'И' . mb_substr($m[0], 1), 'house', 'fix', ['quotes', 'auto']];
            $out[] = ['R-POST', '/\b(?:Президент(?:а|у|ом|е|ы|ов)?|Премьер-министр\w*|Вице-премьер\w*|Вице-министр\w*|Министр(?:а|у|ом|е|ы|ов|ам)?|Аким(?:а|у|ом|е|ы|ов)?|Елбасы|Председател[ьяюеи]\w*|Депутат\w*|Сенатор\w*|Спикер\w*|Глав(?:а|ы|е|у|ой)[\x{20}\x{A0}]+государства|Перв\w+[\x{20}\x{A0}]+[Пп]резидент\w*)\b/u',
                static fn (array $m): string => mb_strtolower($m[0]), 'house', 'fix', ['midsentence', 'not_after_admin']];
            $out[] = ['R-AKIMAT', '/\b(?:Акимат|Маслихат)\w*/u', static fn (array $m): string => mb_strtolower(mb_substr($m[0], 0, 1)) . mb_substr($m[0], 1), 'house', 'fix', ['midsentence']];
            // «г.» после числа — «год», «т. г.», «п. г.», «с. г.» — «текущего», «прошлого», «сего года»
            $out[] = ['R-CITY', '/(?:\b[Гг]ород(?:а|е|у|ом)?|(?<![\d][\x{20}\x{A0}])(?<![\d])(?<![тпсТПС]\.[\x{20}\x{A0}])(?<![тпсТПС]\.)\bг\.)[\x{20}\x{A0}]+(?=\p{Lu}\p{Ll})/u', '', 'house', 'fix', []];
            // техника — в оригинале без кавычек (п. 30), но только техника: «АО «ForteBank»» — юридическое название, его не трогаем
            $out[] = ['R-BRAND', '/«([A-Za-z][A-Za-z0-9&.\'’+ \-]{0,40}[A-Za-z0-9])»/u', '$1', 'house', 'warn', ['quotes', 'tech_context']];
        }

        if (\in_array('units', $groups, true)) {
            $out[] = ['R-MLN', '/(?<=\d[\x{20}\x{A0}]|\d)(млн|млрд|трлн|тыс)(\.?)(?![\p{L}])/u', null, 'house', 'warn', ['quotes', 'agree_mag']];
            $out[] = ['R-UNIT', '/(?<=\d[\x{20}\x{A0}])(?!т\.[\x{20}\x{A0}]*е\.)(км|кг|т|м|см|мм|л|ч|мин|га|кВт|МВт|ГВт)(\.?)(?![\p{L}\d²³])/u', null, 'house', 'warn', ['quotes', 'agree_unit']];
            $out[] = ['R-ADDR', '/\b(ул|пр-т|пр|мкр|р-н|пер|пл|ш)(\.?)(?=[\x{20}\x{A0}]+(?:\p{Lu}|\d))/u', null, 'house', 'warn', ['quotes', 'agree_addr']];
        }

        return $out;
    }

    /** Перед кавычками — слово о технике: автомобиль, самолёт, судно, смартфон, модель. */
    public static function techContext(string $text, int $start): bool
    {
        return (bool) preg_match('/(?:автомобил|машин|самол[её]т|судн|корабл|лайнер|вертол[её]т|модел|марк|смартфон|телефон|ноутбук|кроссовер|седан|внедорожник|грузовик|танкер|автобус|ракет|спутник|электромобил|авто)\w*[\x{20}\x{A0}]+$/u',
            mb_substr($text, max(0, $start - 30), $start - max(0, $start - 30)));
    }

    /** Должность после «Администрации» оставляем: «Администрация Президента» — открытый вопрос к редакции. */
    public static function afterAdmin(string $text, int $start): bool
    {
        return (bool) preg_match('/Администрац\w*[\x{20}\x{A0}]+$/u', mb_substr($text, max(0, $start - 24), $start - max(0, $start - 24)));
    }

    /** Краткое страдательное причастие, а не прилагательное («был должен», «была готова» не в счёт). */
    public static function isParticiple(string $w): bool
    {
        return !preg_match('/^(?:должн|нужн|обязан|способн|согласн|больн|уверен|намерен|склонн|знаком|виден|видн|слышн|полн|известн|интересн|женат|рад|готов|счастлив|един|одинок)/u', $w)
            && !\in_array($w, ['болен', 'должен', 'нужен', 'способен', 'согласен', 'намерен', 'склонен', 'полон', 'умён', 'силён'], true);
    }

    /** Падеж числа по предлогу перед ним: gen, dat, prep, acc; без предлога — именительный (после глагола проверит редактор). */
    public static function caseBefore(string $text, int $numStart, bool $unit): string
    {
        $before = mb_substr($text, max(0, $numStart - 30), $numStart - max(0, $numStart - 30));

        if (!preg_match('/([\p{L}]+)[\x{20}\x{A0}]*[$₸€₽]?$/u', $before, $m)) {
            return 'nom';
        }

        $w = mb_strtolower($m[1]);

        return match (true) {
            \in_array($w, self::GEN, true)   => 'gen',
            \in_array($w, self::DAT, true)   => 'dat',
            \in_array($w, self::PREP, true)  => 'prep',
            $unit && $w === 'в'              => 'prep',     // «в 5 км от» — «в пяти километрах»
            \in_array($w, self::ACC, true)   => 'acc',      // «на 1 тыс.» — «на 1 тысячу»
            default                          => 'nom',
        };
    }

    /**
     * Форма слова при числе: дробное — родительный единственного («1,5 миллиона»); 11–14 — родительный множественного;
     * на 1 — единственное; на 2–4 — родительный единственного в именительном падеже; иначе — родительный множественного.
     */
    public static function agree(array $forms, string $int, string $frac, string $case): string
    {
        if ($frac !== '') {
            return $forms[1];
        }

        $n   = (int) preg_replace('/\D/u', '', $int);
        $k   = $n % 100;
        $d   = $n % 10;
        $one = $d === 1 && ($k < 11 || $k > 14);
        $few = $d >= 2 && $d <= 4 && ($k < 12 || $k > 14);

        return match ($case) {
            'gen'   => $one ? $forms[1] : $forms[2],
            'dat'   => $one ? $forms[3] : $forms[4],
            'prep'  => $one ? $forms[5] : $forms[6],
            'acc'   => $one ? $forms[7] : ($few ? $forms[1] : $forms[2]),
            default => $one ? $forms[0] : ($few ? $forms[1] : $forms[2]),
        };
    }

    /** Правка для «млн», «км», «ул.»: полное слово в форме по числу и предлогу; null — не берёмся. */
    public static function expand(string $kind, string $text, int $start, array $m): ?string
    {
        $before = mb_substr($text, max(0, $start - 40), $start - max(0, $start - 40));

        if ($kind === 'agree_addr') {
            $forms = self::ADDR[$m[1]] ?? null;

            if ($forms === null || ($m[1] === 'пр' && $m[2] === '')) {
                return null;
            }

            preg_match('/([\p{L}]+)[\x{20}\x{A0}]*$/u', $before, $w);
            $p = mb_strtolower($w[1] ?? '');

            return match (true) {
                \in_array($p, ['на', 'в', 'о', 'об', 'при'], true)                                         => $forms[3],
                \in_array($p, ['по', 'к', 'ко'], true)                                                     => $forms[2],
                \in_array($p, ['с', 'со', 'до', 'от', 'у', 'около', 'возле', 'вдоль', 'из', 'для', 'напротив'], true) => $forms[1],
                $w === [] || preg_match('/[.!?…:,;(«]\s*$/u', $before) === 1                              => $forms[0],
                default                                                                                    => null,
            };
        }

        if (!preg_match('/' . self::NUM . '[\x{20}\x{A0}]?$/u', $before, $nm, PREG_OFFSET_CAPTURE)) {
            return null;
        }

        $numStart = mb_strlen(substr($before, 0, $nm[0][1])) + max(0, $start - 40);
        $unit     = $kind === 'agree_unit';
        $forms    = $unit ? (self::UNIT[$m[1]] ?? null) : (self::MAG[$m[1]] ?? null);

        if ($forms === null) {
            return null;
        }

        $word = self::agree($forms, $nm[1][0], $nm[2][0], self::caseBefore($text, $numStart, $unit));

        // точка сокращения в конце предложения остаётся точкой предложения, внутри — уходит вместе с сокращением
        $tail = ($m[2] ?? '') !== '' && preg_match('/^[\x{20}\x{A0}]*(?:$|[«„"(]?\p{Lu})/u', mb_substr($text, $start + mb_strlen($m[0]), 4)) ? '.' : '';

        return $word . $tail;
    }
