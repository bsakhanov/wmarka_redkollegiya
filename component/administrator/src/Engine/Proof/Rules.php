            ['K-POZV', '/\bпозвол(?:яет|яют|ит|ят|ил|ила|ило|или|ять|яя|яющ\w*)\b/iu', null, 'chukovsky', 'info', ['cluster']],
            ['K-OSUSH', '/\bосуществ\w+/iu', null, 'chukovsky', 'info', ['cluster']],
            ['K-RAMK', '/\bв (?:рамках|контексте|свете)\b/iu', null, 'chukovsky', 'info', ['cluster']],
            ['K-PREDST', '/\bпредставля(?:ет|ют|л|ла|ли) собой\b|\bвыступа(?:ет|ют|л|ла|ли) в (?:роли|качестве)\b|\bхарактеризу(?:ется|ются)\b/iu', null, 'chukovsky', 'info', ['cluster']],
