        $pozv = ['позволяет' => 'даёт', 'позволяют' => 'дают', 'позволит' => 'даст', 'позволят' => 'дадут', 'позволил' => 'дал',
            'позволила' => 'дала', 'позволило' => 'дало', 'позволили' => 'дали'];

        return [
            ['K-YAVL', '/\bявля(?:ется|ются|лся|лась|лось|лись|ясь|ющ\w*|вш\w*)\b/iu', null, 'chukovsky', 'info', ['cluster']],
            ['K-DANN', '/\b([Нн])а данный момент\b/u', static fn (array $m): string => $m[1] === 'Н' ? 'Сейчас' : 'сейчас', 'chukovsky', 'info', ['cluster']],
            ['K-DANN', '/\b([Дд])анн(ый|ая|ое|ого|ому|ой|ую|ом)\b/u', static fn (array $m): string => self::likeCase($m[1], $dann[$m[2]]), 'chukovsky', 'info', ['cluster']],
