    /** Повтор слов, которые законно удваивают. */
    public const DOUBLE_OK = ['так', 'да', 'нет', 'ну', 'ой', 'ах', 'эх', 'ха', 'хи', 'тук', 'еле', 'чуть', 'вот', 'бы', 'ли', 'ура', 'ля', 'бом', 'кап'];

    private static function likeCase(string $sample, string $word): string
    {
        return mb_strtoupper(mb_substr($sample, 0, 1)) === mb_substr($sample, 0, 1) && mb_strtolower(mb_substr($sample, 0, 1)) !== mb_substr($sample, 0, 1)
            ? mb_strtoupper(mb_substr($word, 0, 1)) . mb_substr($word, 1)
            : $word;
    }
