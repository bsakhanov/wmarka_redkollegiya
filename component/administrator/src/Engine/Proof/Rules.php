/**
 * Каждое правило: [код, выражение, правка, слой, вес, флаги].
 * Правка — строка с $1…$9 (подстановка групп), замыкание fn(array $m): string, '' (убрать) или null (только флажок).
 * Вес: fix — ошибка с готовой правкой; warn — стоит посмотреть; info — к сведению, решает автор.
 * Флаги: auto — правку можно принять скопом («Принять все надёжные»); quotes — правило работает и внутри цитаты «…»
 * (по умолчанию цитата не трогается: слова говорящего правят только при явной опечатке); cluster — маркер идёт в счёт кластера.
 */
final class Rules
{
    public const LAYERS = ['slop', 'chukovsky', 'rozental', 'yo'];

    /** Следы чат-ботов: работают поодиночке, человек такого не печатает (Слопотрон, «Технические артефакты»). */
    public static function artifacts(): array
    {
        $end = '[^.!?…\n]{0,200}[.!?…]+[\x{20}\x{A0}]*';

        return [
            ['S-CITE', '/[\x{20}\x{A0}]?(?::?contentReference\[[^\]\n]*\](?:\{[^}\n]*\})?|\b(?:oaicite|oai_citation|attributableIndex|grok_card|grok_render_citation_card_json|ppl-ai-file-upload)(?::[\w-]+)*|\bturn\d+(?:search|news|view|file|fetch|image)\d+|【[^】\n]{0,80}】|\[cite:\s*[\d,\s]+\]|\[span_\d+\]\((?:start|end)_span\))/u', '', 'slop', 'fix', ['auto', 'quotes']],
            ['S-TOKEN', '/[\x{20}\x{A0}]?(?:<\|[a-z_]{2,30}\|>|\[MASK\])/u', '', 'slop', 'fix', ['auto', 'quotes']],
            ['S-PUA', '/[\x{E200}-\x{E202}]/u', '', 'slop', 'fix', ['auto', 'quotes']],
            ['S-ENT', '/&(mdash|ndash|nbsp|thinsp|laquo|raquo|ldquo|rdquo|bdquo|hellip);/u', static fn (array $m): string => [
                'mdash' => '—', 'ndash' => '–', 'nbsp' => "\u{00A0}", 'thinsp' => "\u{00A0}", 'laquo' => '«', 'raquo' => '»',
                'ldquo' => '“', 'rdquo' => '”', 'bdquo' => '„', 'hellip' => '…',
            ][$m[1]], 'slop', 'fix', ['auto', 'quotes']],
            // «Конечно, вот черновик статьи:» — рамка кончается двоеточием, за ним уже сам текст
            ['S-FRAME', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))(?:Конечно|Разумеется|Безусловно)[,!]\s+(?:вот|ниже|привожу)\b[^.!?…:\n]{0,200}[.!?…:]+[\x{20}\x{A0}]*/u', '', 'slop', 'fix', ['quotes']],
            ['S-FRAME', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))(?:Я\s+)?[Нн]адеюсь,?\s+(?:что\s+)?(?:это|было|эта|этот|информация|статья|материал|текст)[^.!?…\n]{0,80}полезн' . $end . '/u', '', 'slop', 'fix', ['quotes']],
            ['S-FRAME', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))Если у вас (?:есть|возникнут|возникли|остались) (?:ещё |еще |дополнительные |другие )?вопросы' . $end . '/u', '', 'slop', 'fix', ['quotes']],
            ['S-FRAME', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))Сообщите(?: мне)?,? если' . $end . '/u', '', 'slop', 'fix', ['quotes']],
            // «Как языковая модель, я…» — но не «Как ИИ повлияет на рынок?»: нужна запятая и «я»
            ['S-FRAME', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))(?:Как|Будучи)\s+(?:ИИ|искусственный интеллект|языковая модель|ИИ-модель|нейросеть|модель ИИ),\s*я\b' . $end . '/u', '', 'slop', 'fix', ['quotes']],
            ['S-FRAME', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))Я\s*[—–-]\s*(?:GigaChat|YandexGPT|ChatGPT|Claude|Gemini|большая языковая модель|языковая модель)' . $end . '/u', '', 'slop', 'fix', ['quotes']],
            ['S-FRAME', '/(?:на момент моего (?:обучения|последнего обновления)|по состоянию на (?:моё|мое) последнее обновление|(?:моя|моей) баз[аеы] знаний)/iu', null, 'slop', 'warn', ['quotes']],
            ['S-SMM', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))(?:(?:Делитесь|Поделитесь)(?: своим)?(?: мнением)? в комментариях|Ставьте (?:лайк|реакци\w*|плюс)|Сохраняйте (?:пост|себе)|Спасибо,? что дочитали)' . $end . '/u', '', 'slop', 'warn', ['quotes']],
        ];
    }

    /** Фразы-маркеры нейрослопа (Слопотрон): сигнал даёт стая, а не одиночка. */
    public static function phrases(): array
    {
        $sub = static fn (array $m): string => mb_strtoupper($m[2]);

        return [
            // вводная в начале предложения: «Важно отметить, что рост…» → «Рост…»
            ['S-PHR', '/(?:^|(?<=[.!?…][\x{20}\x{A0}]))((?:Важно|Стоит|Следует|Необходимо|Нужно|Хочется)\s+(?:отметить|подчеркнуть|учитывать|сказать|заметить)|Не секрет|Всем известно|Ни для кого не секрет),?\s+что\s+(\p{L})/u', $sub, 'slop', 'info', ['cluster']],
            ['S-PHR', '/\b(?:в современном мире|в наше время|в эпоху цифровизации|подводя итог\w*|таким образом,? можно сделать вывод|давайте разбер[её]мся|что это значит для вас|представьте себе|это особенно важно для|игра(?:ет|ют|л|ла|ли) (?:важную|ключевую|огромную|решающую) роль|(?:служит|выступает|является) напоминанием|оставил[аи]? неизгладимый след|(?:ключевой|поворотный) момент|данные говорят|практика показывает|рынок диктует|вот в ч[её]м дело|чего вам никто не скажет|и вот что интересно|знакомо\?|узнали себя\?|звучит знакомо\?)/iu', null, 'slop', 'info', ['cluster']],
        ];
    }

    /** Псевдомодальные обороты (Слопотрон): «может стать», «способен обеспечить». В новостях это обычный язык прогноза. */
    public static function modal(): array
    {
        return [
            ['S-PHR', '/\b(?:может|могут) стать\b|\bспособ(?:ен|на|но|ны) обеспечить\b|\bпризван[аоы]? (?:решить|обеспечить|стать)\b/iu', null, 'slop', 'info', ['cluster']],
        ];
    }

    /** Слова-маркеры нейрослопа (Слопотрон). В новостях, науке и юридическом тексте — норма жанра: там не проверяются. */
    public static function words(): array
    {
        return [
            ['S-WORD', '/\b(?:обеспечива\w*|способству\w*|демонстриру\w*|свидетельству\w*|ключев(?:ой|ая|ое|ые|ого|ым|ыми|ых|ую|ом)|значительн\w*|существенн\w*|фундаментальн\w*|беспрецедентн\w*|ландшафт\w*|экосистем\w*|синерги\w*|уникальн\w*|инновационн\w*|революционн\w*|передов(?:ой|ая|ое|ые|ого|ым|ыми|ых|ую|ом)|бесш[ао]вн\w*|тщательн\w*|своевременн\w*|минимизир\w*)\b/iu', null, 'slop', 'info', ['cluster']],
        ];
    }

