// ------------------------------------------------------------------ повторный прогон ничего не меняет

$samples = [
    '<p>Он сказал: "Нацбанк - регулятор, ставка -0.25 п.п., рост 1.5 млрд..." И т.д.</p><ul><li>в 2020-2025 гг.</li></ul>',
